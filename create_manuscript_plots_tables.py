def _missing(step: Step) -> list[str]:
    missing = []
    for item in step.requires:
        alternatives = item if isinstance(item, tuple) else (item,)
        if not any(os.path.exists(f) for f in alternatives):
            missing.append(" or ".join(alternatives))
    return missing


def main(argv: list[str] | None = None) -> int:
    all_steps = steps()
    ap = argparse.ArgumentParser(description="Generate all figures and tables of the manuscript and its SI.",
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="+", metavar="STEP", choices=[s.key for s in all_steps],
                    help="run only these steps (see --list)")
    ap.add_argument("--list", action="store_true", help="list the steps and exit")
    ap.add_argument("--recompute", action="store_true",
                    help="draw and evaluate the missing Monte-Carlo samples of the convergence study (about 2 h)")
    ap.add_argument("--show", action="store_true", help="display the figures in addition to saving them")
    args = ap.parse_args(argv)

    if args.list:
        for s in all_steps:
            print(f"{s.key:8s} {s.target:58s} {s.outputs}")
        return 0

    import matplotlib
    if not args.show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from visualization.style import register_iciw_styles
    register_iciw_styles()               # some modules use the ICIW style by name (Linux, macOS)

    os.makedirs(FIGURES, exist_ok=True)
    os.makedirs(TABLES, exist_ok=True)
    if args.recompute:
        from analysis.mc_sampling import run as run_mc_sampling
        run_mc_sampling()

    selected = [s for s in all_steps if args.only is None or s.key in args.only]
    failed, skipped = [], []
    for s in selected:
        missing = _missing(s)
        if missing:
            print(f"[skip] {s.key} ({s.target}): missing {', '.join(missing)}")
            skipped.append(s.key)
            continue
        print(f"[run]  {s.key} ({s.target})", flush=True)
        t0 = time.time()
        matplotlib.rc_file_defaults()    # every step starts from the same style, as when run alone
        try:
            s.run(args)
        except Exception:                # report and continue with the other outputs
            traceback.print_exc()
            failed.append(s.key)
        finally:
            plt.close("all")
        print(f"       {time.time() - t0:.0f} s", flush=True)
    print(f"done: {len(selected) - len(failed) - len(skipped)} steps, skipped: {skipped or 'none'}, "
          f"failed: {failed or 'none'}")
    return 1 if failed else 0


if __name__ == "__main__":
    os.chdir(ROOT)                       # the repository uses paths relative to its root
    if ROOT not in sys.path:
        sys.path.insert(0, ROOT)
    sys.exit(main())
