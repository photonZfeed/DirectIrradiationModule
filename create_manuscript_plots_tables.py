"""
Generate all figures and tables of the manuscript and its Supporting Information.

Every output that the code of this repository produces is generated by one step; ``--list`` shows
them. Figures are written to ``figures/`` (SVG), tables to ``tables/`` (CSV). Figures 4 and 5 were
arranged in Inkscape for the publication. Figure 2, the photographs and CAD drawings (Figures 1b,
1c, 6b-f, S2-S4), Figure S1 and Tables 1, S1 and S2 are not generated by the code.

The Monte-Carlo convergence study (Table S5, Supporting Information S12, Figures S18 and S19) reads
the samples and metrics of ``results/geometric/monte_carlo_convergence/`` (about 2.1 GB, part of
the Zenodo dataset). Figure 5 reads the 5 million-sample optimization or simulation results of
``results/geometric/<LED>/`` (Zenodo). Steps whose data are missing are skipped with a message.
``--recompute`` draws and evaluates the Monte-Carlo samples whose files are missing (about two hours on
two cores for all four seeds); delete existing files to redo them.

**Usage** (from any folder)::

    python create_manuscript_plots_tables.py                 # all figures and tables
    python create_manuscript_plots_tables.py --list          # list the steps
    python create_manuscript_plots_tables.py --only fig3 tabS4
    python create_manuscript_plots_tables.py --recompute     # also draw missing Monte-Carlo samples
    python create_manuscript_plots_tables.py --show          # display the figures as well
"""
from __future__ import annotations

import argparse
import os
import sys
import time
import traceback
from dataclasses import dataclass, field
from typing import Callable

ROOT = os.path.dirname(os.path.abspath(__file__))
#: Output folder of the figures (relative to the repository root).
FIGURES = "figures"
#: Output folder of the tables (relative to the repository root).
TABLES = "tables"
#: Float format of the tables.
FLOAT_FORMAT = "%.6g"


@dataclass
class Step:
    """One output of the manuscript: identifier, what it is, how it is made and what it needs."""

    key: str
    target: str
    outputs: str
    run: Callable[[argparse.Namespace], None]
    #: Files the step needs; a tuple stands for alternatives of which one is enough.
    requires: list[str | tuple[str, ...]] = field(default_factory=list)


def _table(df, name: str) -> None:
    path = os.path.join(TABLES, name)
    df.to_csv(path, index=False, float_format=FLOAT_FORMAT)
    print(f"  written {path}")


